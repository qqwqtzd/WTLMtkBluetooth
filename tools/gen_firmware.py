"""Turn the MediaTek Bluetooth firmware in firmware/ into a C file the MtkBt kext links in.

  python3 tools/gen_firmware.py <out.c>

MT7925 comes from linux-firmware (mediatek/mt7925); MT7927/MT6639 is the
MediaTek blob extracted from the vendor driver (mediatek/mt7927). Each SHA-256
is checked against firmware/SHA256SUMS and embedded, so the driver can publish
which firmware it carries.
"""
import hashlib
import sys
from pathlib import Path

FW = Path(__file__).resolve().parents[1] / "firmware"
BLOBS = [
    ("mtk_bt_fw", "BT_RAM_CODE_MT7925_1_1_hdr.bin", "mediatek/mt7925"),
    ("mtk_bt_fw_7927", "BT_RAM_CODE_MT6639_2_1_hdr.bin", "mediatek/mt7927"),
]


def pinned():
    out = {}
    for line in (FW / "SHA256SUMS").read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) == 2 and len(parts[0]) == 64:
            out[parts[1].lstrip("*")] = parts[0]
    return out


def main(dst):
    sums = pinned()
    lines = ["// generated by tools/gen_firmware.py from firmware/, do not edit",
             "#include <stdint.h>"]
    for sym, name, dirname in BLOBS:
        data = (FW / name).read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        if sums.get(name) != digest:
            sys.exit(f"{name}: sha256 {digest} does not match firmware/SHA256SUMS")
        lines.append(f"const unsigned int {sym}_len = {len(data)}u;")
        lines.append(f'const char {sym}_sha256[] = "{digest}";')
        lines.append(f'const char {sym}_name[] = "{dirname}/{name}";')
        lines.append(f"const unsigned char {sym}[] __attribute__((aligned(16))) = {{")
        for i in range(0, len(data), 16):
            lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        lines.append("};")
        lines.append("")
    Path(dst).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{dst}: {', '.join(name for _, name, _ in BLOBS)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
